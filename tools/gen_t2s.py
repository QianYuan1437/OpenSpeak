"""Regenerates lib/core/t2s_table.dart from OpenCC's TSCharacters.txt.

Usage: curl -LO https://raw.githubusercontent.com/BYVoid/OpenCC/master/data/dictionary/TSCharacters.txt
       python3 tools/gen_t2s.py TSCharacters.txt
"""
import os
import sys

src = sys.argv[1]
pairs = []
for line in open(src, encoding='utf-8'):
    line = line.strip()
    if not line or line.startswith('#'):
        continue
    t, s = line.split('\t')
    s = s.split(' ')[0]
    if len(t) == 1 and len(s) == 1 and t != s:
        pairs.append(t + s)
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
with open(os.path.join(root, 'lib', 'core', 't2s_table.dart'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/gen_t2s.py from OpenCC TSCharacters.txt\n'
            '// (https://github.com/BYVoid/OpenCC, Apache-2.0). Do not edit.\n\n'
            '/// Traditional→Simplified character pairs, two characters per entry.\n'
            "const kT2SPairs =\n    '%s';\n" % ''.join(pairs))
print(len(pairs), 'pairs')
